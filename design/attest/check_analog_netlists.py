#!/usr/bin/env python3
"""Freshness check for one derived analog netlist (T1 item 1, analog partition).

    python3 -I design/attest/check_analog_netlists.py <schematic.sch> <netlist.spice>

Re-runs `klt netlist <schematic> --rcfile design/xschemrc --block` into a scratch
file and exits 0 only if the committed netlist still reproduces it. Exit 3 = the
schematic and the committed netlist disagree; exit 1 = the netlister failed.
Needs xschem, so the inventory marks this check local_only.

Why not `klt netlist --check` directly
--------------------------------------
xschem writes the *absolute path of the checkout that produced it* into every
netlist (`** sch_path:`, `** sym_path:`), so the committed netlists on main carry
the paths of the worktrees they were generated in (`issue-41`, `issue-51`,
`issue-92`, `pr-99`). A byte-level comparison therefore reports drift for anyone
who is not working in that exact directory, and `klt netlist --check` under this
repo's pinned klt (.github/klt-version, 0.8.0) is byte-level. klt 0.9.x normalizes
those comments internally, so the same check passes there and fails here -- a
freshness verdict that depends on the checkout path and the klt build is not
evidence of anything about the design.

This script compares what the netlist actually asserts about the circuit. It first
drops exactly three kinds of generator-environment comment:

  ** sch_path: <abs>          filesystem path of the generating checkout
  ** sym_path: <abs>          filesystem path of an instantiated symbol
  ** klt-netlist-inputs: {..} rcfile/pdk/xschem version of the generating host
                              (emitted by klt 0.9.x, absent under 0.8.0)

None of the three carries circuit information.

It then joins SPICE continuation lines (`+ ...`) back onto the statement they
continue and collapses runs of whitespace, because xschem wraps a device line at
a column width that varies between runs: the committed `clkgen.spice` wraps at
~100 columns and a fresh run here wraps at ~128, with identical devices,
parameters and ordering. Continuation is SPICE syntax for "this is still the
previous line", so an unwrapped comparison is the comparison that means
something. klt 0.9.x normalizes both the paths and the wrapping inside
`--check`, which is why that check passes there and fails under the pinned
0.8.0; this script makes the same comparison explicitly instead of depending on
which klt build happens to be installed.

What is compared is therefore the full statement list: the `.subckt` port line
with its port order, every device with its nets and parameters, every `*.iopin`,
and `.ends`. The toolchain a recorded result was produced with is pinned and
reported separately (sim/toolchain.json, sim/pdk.json); it is not re-asserted
here, and this check does not claim the committed netlist was generated by any
particular xschem or klt build.
"""
import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[2]
RCFILE = REPO / "design" / "xschemrc"

# Generator-environment comments: path of the generating checkout, and the
# klt/xschem input stamp. Dropped from both sides before comparing.
DROP = re.compile(rb"^\*\* (?:sch_path|sym_path|klt-netlist-inputs):")


def statements(raw: bytes) -> list[str]:
    """Canonical statement list: comments dropped, continuations joined, spaces collapsed."""
    out: list[str] = []
    for line in raw.decode(errors="replace").splitlines():
        if DROP.match(line.encode()):
            continue
        if line.startswith("+"):
            if not out:
                out.append("")
            out[-1] = f"{out[-1]} {line[1:].strip()}".strip()
        else:
            out.append(line.strip())
    return [re.sub(r"\s+", " ", s) for s in out if s.strip()]


def main(argv):
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 1
    sch, spice = (REPO / p for p in argv)
    for p in (sch, spice):
        if not p.is_file():
            print(f"missing: {p.relative_to(REPO)}", file=sys.stderr)
            return 1

    with tempfile.TemporaryDirectory() as tmp:
        fresh = pathlib.Path(tmp) / spice.name
        cmd = ["klt", "netlist", str(sch), "-o", str(fresh),
               "--rcfile", str(RCFILE), "--block"]
        o = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
        if o.returncode or not fresh.is_file():
            print(f"klt netlist failed (exit {o.returncode}):\n{o.stdout}{o.stderr}",
                  file=sys.stderr)
            return 1
        want, have = statements(fresh.read_bytes()), statements(spice.read_bytes())

    rel = spice.relative_to(REPO)
    if want != have:
        import difflib
        print(f"DRIFT: {rel} does not reproduce from {sch.relative_to(REPO)}; "
              f"regenerate it (design/README.md, 'Regenerating netlists')",
              file=sys.stderr)
        sys.stderr.writelines(difflib.unified_diff(
            [f"{s}\n" for s in have], [f"{s}\n" for s in want],
            fromfile=f"{rel} (committed)", tofile=f"{rel} (regenerated)", n=1))
        return 3
    print(f"fresh: {rel} ({len(have)} statements)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
