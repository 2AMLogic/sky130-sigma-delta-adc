#!/usr/bin/env bash
#
# design/modulator/comparator/wrap_comparator.sh -- bind the vendored
# comparator device lines into a subcircuit with this repo's port names.
#
#   comparator_core.spice  (verbatim from sky130-comparator, see PROVENANCE.md)
#       --(this script)-->  comparator.spice
#
# The upstream fragment is flat: supplies are the global names VDD/GND and
# there is no .subckt. Only two mechanical edits are made, and no device line
# is otherwise touched: the upstream header comment is dropped, and the net
# names VDD and GND become the ports vdda and vssa so the comparator sits on
# the same analog rails as the rest of the modulator (DR-004) instead of being
# tied to ngspice's global node 0. Port order matches comparator.sym:
#   vdda vssa clk vinp vinn outp outn
#
# Usage (from the repository root):
#   design/modulator/comparator/wrap_comparator.sh          # rewrite comparator.spice
#   design/modulator/comparator/wrap_comparator.sh --check  # diff only; exit 1 if stale

set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="${DIR}/comparator_core.spice"
OUT="${DIR}/comparator.spice"

NEW="$(mktemp)"
trap 'rm -f "${NEW}"' EXIT

{
  echo "* comparator -- sky130-comparator wrapped as a subcircuit (issue #41)."
  echo "* GENERATED by design/modulator/comparator/wrap_comparator.sh from the"
  echo "* vendored comparator_core.spice (provenance: PROVENANCE.md). Do not hand-edit."
  echo ".subckt comparator vdda vssa clk vinp vinn outp outn"
  grep -E '^(X|\+)' "${SRC}" | sed -E 's/\bVDD\b/vdda/g; s/\bGND\b/vssa/g'
  echo ".ends comparator"
} > "${NEW}"

N_DEV="$(grep -c '^X' "${NEW}")"
if [[ "${N_DEV}" -ne 16 ]]; then
  echo "wrap_comparator.sh: expected 16 device lines (13 MOSFETs + 3 resistors), got ${N_DEV}" >&2
  exit 1
fi

if [[ "${1:-}" == "--check" ]]; then
  if diff -u "${OUT}" "${NEW}"; then
    echo "wrap_comparator.sh --check: comparator.spice is up to date"
  else
    echo "wrap_comparator.sh --check: STALE -- re-run wrap_comparator.sh" >&2
    exit 1
  fi
else
  cp "${NEW}" "${OUT}"
  echo "wrap_comparator.sh: wrote ${OUT##*/}"
fi
