#!/usr/bin/env python3
"""Design the linear-phase FIR and write rtl/decimator_coef.v.

Minimax design (linear program, scipy/HiGHS): minimise the stopband peak over
60-160 kHz (at the 320 kSps FIR input rate) subject to the whole-chain passband
(CIC x FIR) staying within +/-RIPPLE_DB of flat over 0-20 kHz and unity DC
gain. Coefficients are then rounded to COEF_FRAC fractional bits and the DC sum
is forced to exactly 2**COEF_FRAC by putting the rounding residue (a few LSB)
on the centre tap, which keeps the filter symmetric (linear phase).

This script is the only place the design intent lives; response.py then judges
the *quantized numbers in the generated file*, not this script's floats.
"""
import sys
import numpy as np
from scipy.optimize import linprog

import model as m

RIPPLE_DB = 0.02          # design half-ripple; spec limit is 0.1 dB peak-to-peak
STOP_LO, STOP_HI = 60e3, 160e3


def cic_np(f):
    f = np.asarray(f, float)
    x = np.pi * f / m.FS
    with np.errstate(all="ignore"):
        h = np.where(np.abs(np.sin(x)) < 1e-15, 1.0, np.sin(m.CIC_R * x) / (m.CIC_R * np.sin(x)))
    return np.abs(h) ** m.CIC_N


def design():
    f2 = m.FS / m.CIC_R
    M = (m.N_TAPS - 1) // 2

    def basis(f):
        w = 2 * np.pi * np.asarray(f) / f2
        return np.hstack([np.ones((len(f), 1))] + [2 * np.cos(w * n)[:, None] for n in range(1, M + 1)])

    fp = np.linspace(0, m.BW, 201)
    fs_ = np.linspace(STOP_LO, STOP_HI, 1001)
    Ap, As = basis(fp), basis(fs_)
    D = 1 / cic_np(fp)
    d = 10 ** (RIPPLE_DB / 20) - 1
    z1 = lambda n: np.zeros((n, 1))
    rows = [np.hstack([Ap, z1(len(fp))]), np.hstack([-Ap, z1(len(fp))]),
            np.hstack([As, -np.ones((len(fs_), 1))]), np.hstack([-As, -np.ones((len(fs_), 1))])]
    b = [D * (1 + d), -D * (1 - d), np.zeros(len(fs_)), np.zeros(len(fs_))]
    c = np.zeros(M + 2)
    c[-1] = 1
    r = linprog(c, A_ub=np.vstack(rows), b_ub=np.concatenate(b),
                A_eq=np.hstack([basis(np.array([0.0])), [[0.0]]]), b_eq=[1.0],
                bounds=[(None, None)] * (M + 2), method="highs")
    if r.status != 0:
        sys.exit(f"LP failed: {r.message}")
    a = r.x[:-1]
    return np.concatenate([a[:0:-1], a]), r.x[-1]


def quantize(h):
    q = np.round(h * (1 << m.COEF_FRAC)).astype(int)
    resid = (1 << m.COEF_FRAC) - int(q.sum())
    mid = m.N_TAPS // 2
    q[mid] += resid
    return [int(v) for v in q]


def emit(q, path):
    lo, hi = -(1 << (m.COEF_W - 1)), (1 << (m.COEF_W - 1)) - 1
    assert all(lo <= v <= hi for v in q), "coefficient exceeds COEF_W"
    lines = [
        "// GENERATED by verification/decimator/design_fir.py - do not edit by hand.",
        f"// {m.N_TAPS}-tap linear-phase FIR at {m.FS / m.CIC_R / 1e3:.0f} kSps, coefficients are",
        f"// signed {m.COEF_W}-bit integers scaled by 2**-{m.COEF_FRAC}; the sum is exactly 2**{m.COEF_FRAC}.",
        "`timescale 1ns/1ps",
        "module decimator_coef (",
        "    input  wire [5:0]        k,",
        f"    output reg  signed [{m.COEF_W - 1}:0] h",
        ");",
        "    always @* begin",
        "        case (k)",
    ]
    lines += [f"            6'd{n}: h = {v};" for n, v in enumerate(q)]
    lines += ["            default: h = 0;", "        endcase", "    end", "endmodule", ""]
    path.write_text("\n".join(lines))


if __name__ == "__main__":
    h, t = design()
    q = quantize(h)
    emit(q, m.COEF_V)
    print(f"float stopband peak {20 * np.log10(t):.1f} dB; wrote {m.COEF_V}")
